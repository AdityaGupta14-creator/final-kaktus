/**
 * Kaktus Hardware Bridge Autostart Manager
 * 
 * Configures user-level automatic startup for the local hardware bridge upon Windows login.
 * Does NOT require administrator privileges.
 * 
 * Usage:
 *   node scripts/manage-bridge-autostart.js enable
 *   node scripts/manage-bridge-autostart.js disable
 *   node scripts/manage-bridge-autostart.js status
 */

const fs = require('fs');
const path = require('path');
const os = require('os');
const { checkBridgeHealth, getPortOccupant } = require('./hardware-bridge-launcher');

const rootDir = path.resolve(__dirname, '..');
const launcherScript = path.join(rootDir, 'scripts', 'hardware-bridge-launcher.js');

/**
 * Resolves the autostart destination path based on the operating system.
 */
function getAutostartConfig() {
  const platform = process.platform;
  if (platform === 'win32') {
    const appData = process.env.APPDATA || path.join(os.homedir(), 'AppData', 'Roaming');
    const startupDir = path.join(appData, 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup');
    const targetFile = path.join(startupDir, 'kaktus-hardware-bridge.vbs');
    return { platform: 'windows', targetDir: startupDir, targetFile };
  } else if (platform === 'darwin') {
    const targetDir = path.join(os.homedir(), 'Library', 'LaunchAgents');
    const targetFile = path.join(targetDir, 'com.kaktus.hardware-bridge.plist');
    return { platform: 'darwin', targetDir, targetFile };
  } else {
    const targetDir = path.join(os.homedir(), '.config', 'autostart');
    const targetFile = path.join(targetDir, 'kaktus-hardware-bridge.desktop');
    return { platform: 'linux', targetDir, targetFile };
  }
}

/**
 * Enables auto-start on user login.
 */
function enableAutostart() {
  const config = getAutostartConfig();
  console.log(`Configuring login autostart for ${config.platform}...`);

  if (!fs.existsSync(config.targetDir)) {
    fs.mkdirSync(config.targetDir, { recursive: true });
  }

  if (config.platform === 'windows') {
    // VBScript executes node launcher with --daemon mode hidden (window style 0 = invisible)
    // No terminal flashes on Windows login.
    const escapedProjectDir = rootDir.replace(/"/g, '""');
    const escapedLauncher = launcherScript.replace(/"/g, '""');
    const nodeExe = process.execPath.replace(/"/g, '""');

    const vbsContent = [
      `' Kaktus Hardware Bridge User-Level Autostart`,
      `' Automatically generated by npm run hardware:autostart:enable`,
      `' Safe, user-level startup entry. To disable, run: npm run hardware:autostart:disable`,
      `Set WshShell = CreateObject("WScript.Shell")`,
      `WshShell.CurrentDirectory = "${escapedProjectDir}"`,
      `WshShell.Run """${nodeExe}"" ""${escapedLauncher}"" --daemon", 0, False`,
      `Set WshShell = Nothing`,
      ``,
    ].join('\r\n');

    fs.writeFileSync(config.targetFile, vbsContent, 'utf8');
    console.log('✓ Successfully enabled hardware bridge autostart on Windows login.');
    console.log(`  Installed startup launcher at:`);
    console.log(`  ${config.targetFile}`);
    console.log(`\nHow to verify:`);
    console.log(`  - Press Win + R, type 'shell:startup' and press Enter to view the startup script.`);
    console.log(`  - Or check status anytime with: npm run hardware:autostart:status`);
    console.log(`\nHow to disable:`);
    console.log(`  - Run: npm run hardware:autostart:disable`);
    return { ok: true, file: config.targetFile };
  } else if (config.platform === 'darwin') {
    const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>com.kaktus.hardware-bridge</string>
  <key>ProgramArguments</key>
  <array>
    <string>${process.execPath}</string>
    <string>${launcherScript}</string>
    <string>--daemon</string>
  </array>
  <key>WorkingDirectory</key>
  <string>${rootDir}</string>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <false/>
</dict>
</plist>`;
    fs.writeFileSync(config.targetFile, plist, 'utf8');
    console.log('✓ Successfully enabled hardware bridge LaunchAgent.');
    console.log(`  Installed at: ${config.targetFile}`);
    return { ok: true, file: config.targetFile };
  } else {
    const desktop = `[Desktop Entry]
Type=Application
Version=1.0
Name=Kaktus Hardware Bridge
Comment=Kaktus Local Hardware USB Service
Exec=${process.execPath} "${launcherScript}" --daemon
Path=${rootDir}
Terminal=false
Hidden=false
`;
    fs.writeFileSync(config.targetFile, desktop, 'utf8');
    console.log('✓ Successfully enabled autostart desktop entry.');
    console.log(`  Installed at: ${config.targetFile}`);
    return { ok: true, file: config.targetFile };
  }
}

/**
 * Disables auto-start on user login.
 */
function disableAutostart() {
  const config = getAutostartConfig();
  if (fs.existsSync(config.targetFile)) {
    fs.unlinkSync(config.targetFile);
    console.log('✓ Successfully disabled hardware bridge autostart.');
    console.log(`  Removed startup entry: ${config.targetFile}`);
    return { ok: true, removed: true };
  } else {
    console.log('Hardware bridge autostart is not currently enabled.');
    console.log(`  No startup entry found at: ${config.targetFile}`);
    return { ok: true, removed: false };
  }
}

/**
 * Checks current auto-start status and bridge runtime state.
 */
async function checkStatus() {
  const config = getAutostartConfig();
  const isEnabled = fs.existsSync(config.targetFile);
  const health = await checkBridgeHealth(8000, 2000);
  const occupant = getPortOccupant(8000);

  console.log('=== Kaktus Hardware Bridge Autostart Status ===');
  console.log(`Platform:               ${config.platform}`);
  console.log(`Autostart Enabled:      ${isEnabled ? 'YES' : 'NO'}`);
  console.log(`Autostart File:         ${config.targetFile}`);
  console.log(`Autostart File Exists:  ${isEnabled ? 'Yes' : 'No'}`);
  console.log('-----------------------------------------------');
  console.log(`Bridge Running:         ${health.ok ? 'YES' : 'NO'}`);
  console.log(`Bridge Healthy:         ${health.isKaktus ? 'YES' : 'NO'}`);
  console.log(`Listening Port:         8000`);
  console.log(`Occupying PID:          ${occupant?.pid || 'None'}${occupant?.name ? ` (${occupant.name})` : ''}`);
  console.log('===============================================');

  return { isEnabled, config, health, occupant };
}

// CLI Handling
if (require.main === module) {
  const command = process.argv[2] || 'status';
  if (command === 'enable' || command === '--enable') {
    enableAutostart();
  } else if (command === 'disable' || command === '--disable') {
    disableAutostart();
  } else if (command === 'status' || command === '--status') {
    checkStatus();
  } else {
    console.log('Usage:');
    console.log('  node scripts/manage-bridge-autostart.js enable');
    console.log('  node scripts/manage-bridge-autostart.js disable');
    console.log('  node scripts/manage-bridge-autostart.js status');
    process.exit(1);
  }
}

module.exports = {
  getAutostartConfig,
  enableAutostart,
  disableAutostart,
  checkStatus,
};
